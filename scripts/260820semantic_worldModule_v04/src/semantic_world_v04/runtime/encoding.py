"""Deterministic image and semantic encoders."""

import hashlib
import io
from typing import Any, Dict, Mapping, Tuple


def jsonable(value: Any) -> Any:
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    if isinstance(value, Mapping):
        return {str(key): jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [jsonable(item) for item in value]
    if hasattr(value, "tolist"):
        return jsonable(value.tolist())
    return str(value)


def encode_npy(array: Any) -> bytes:
    import numpy as np

    stream = io.BytesIO()
    np.save(stream, np.asarray(array), allow_pickle=False)
    return stream.getvalue()


def encode_png(array: Any) -> bytes:
    import numpy as np
    from PIL import Image

    value = np.asarray(array)
    if value.dtype.kind == "f":
        maximum = float(value.max()) if value.size else 0.0
        if maximum <= 1.0:
            value = value * 255.0
        value = np.clip(value, 0, 255).astype(np.uint8)
    elif value.dtype != np.uint8:
        value = np.clip(value, 0, 255).astype(np.uint8)
    if value.ndim == 3 and value.shape[-1] == 4:
        value = value[..., :3]
    image = Image.fromarray(value)
    stream = io.BytesIO()
    image.save(stream, format="PNG", compress_level=4)
    return stream.getvalue()


def encode_npz(arrays: Mapping[str, Any]) -> bytes:
    import numpy as np

    if not arrays:
        raise ValueError("NPZ output requires at least one named array")
    stream = io.BytesIO()
    np.savez_compressed(
        stream,
        **{str(name): np.asarray(value) for name, value in arrays.items()},
    )
    return stream.getvalue()


def encode_point_cloud_ply(payload: Any) -> bytes:
    """Encode XYZ plus optional scalar fields as an ASCII PLY artifact."""

    import numpy as np

    if isinstance(payload, Mapping):
        if "points" in payload:
            points = np.asarray(payload["points"])
        elif all(name in payload for name in ("x", "y", "z")):
            points = np.column_stack((payload["x"], payload["y"], payload["z"]))
        else:
            raise ValueError("point cloud mapping must contain points or x/y/z")
        extras = {
            str(name): np.asarray(value).reshape(-1)
            for name, value in payload.items()
            if name not in {"points", "x", "y", "z"}
            and np.asarray(value).ndim <= 1
        }
    else:
        points = np.asarray(payload)
        extras = {}
    if points.ndim != 2 or points.shape[1] < 3:
        raise ValueError("point cloud must have shape Nx3 or wider")
    points = points[:, :3].astype(np.float64, copy=False)
    if not np.isfinite(points).all():
        raise ValueError("point cloud contains non-finite XYZ values")
    count = int(points.shape[0])
    for name, value in extras.items():
        if len(value) != count:
            raise ValueError(f"point field {name} length differs from XYZ")
    safe_extras = {
        name: value
        for name, value in extras.items()
        if name.replace("_", "").isalnum()
    }
    header = [
        "ply",
        "format ascii 1.0",
        "comment generated by semantic_world_v04",
        f"element vertex {count}",
        "property double x",
        "property double y",
        "property double z",
    ]
    for name in sorted(safe_extras):
        header.append(f"property double {name}")
    header.append("end_header")
    rows = []
    names = sorted(safe_extras)
    for index, point in enumerate(points):
        values = [*point, *(safe_extras[name][index] for name in names)]
        rows.append(" ".join(f"{float(value):.12g}" for value in values))
    return ("\n".join(header + rows) + "\n").encode("ascii")


def colorize_depth(array: Any, *, minimum: float = 0.0, maximum: float = 0.0) -> Any:
    import numpy as np

    value = np.asarray(array, dtype=np.float32)
    value = np.squeeze(value)
    if value.ndim != 2:
        raise ValueError(f"depth array must be HxW, got {value.shape}")
    finite = np.isfinite(value) & (value > 0)
    if not finite.any():
        return np.zeros((*value.shape, 3), dtype=np.uint8)
    lower = float(minimum) if minimum > 0 else float(value[finite].min())
    upper = float(maximum) if maximum > lower else float(value[finite].max())
    if upper <= lower:
        upper = lower + 1.0
    normalized = np.zeros(value.shape, dtype=np.float32)
    normalized[finite] = np.clip((value[finite] - lower) / (upper - lower), 0, 1)
    # Blue-near, green-mid, red-far; deterministic and dependency-free.
    red = np.clip(2.0 * normalized - 0.5, 0, 1)
    green = np.clip(1.5 - 2.0 * np.abs(normalized - 0.5), 0, 1)
    blue = np.clip(1.5 - 2.0 * normalized, 0, 1)
    color = np.stack((red, green, blue), axis=-1)
    color[~finite] = 0
    return (color * 255.0).astype(np.uint8)


def colorize_normals(array: Any) -> Any:
    import numpy as np

    value = np.asarray(array, dtype=np.float32)
    if value.ndim != 3 or value.shape[-1] < 3:
        raise ValueError(f"normal array must be HxWx3, got {value.shape}")
    value = value[..., :3]
    return np.clip((value * 0.5 + 0.5) * 255.0, 0, 255).astype(np.uint8)


class SemanticPalette:
    """Stable ID colors plus labels learned from annotator metadata."""

    def __init__(self) -> None:
        self.labels: Dict[int, Any] = {}

    @staticmethod
    def color_for_id(semantic_id: int) -> Tuple[int, int, int]:
        if semantic_id == 0:
            return (0, 0, 0)
        digest = hashlib.sha256(
            f"semantic-world-v04:{semantic_id}".encode("ascii")
        ).digest()
        # Avoid nearly black colors while preserving deterministic output.
        return tuple(48 + (channel % 208) for channel in digest[:3])

    def update_from_info(self, info: Mapping[str, Any]) -> bool:
        raw = info.get("idToLabels") or info.get("idToLabel") or {}
        if not isinstance(raw, Mapping):
            return False
        changed = False
        for raw_id, label in raw.items():
            try:
                semantic_id = int(raw_id)
            except (TypeError, ValueError):
                continue
            normalized = jsonable(label)
            if self.labels.get(semantic_id) != normalized:
                self.labels[semantic_id] = normalized
                changed = True
        return changed

    def colorize(self, semantic_ids: Any) -> Any:
        import numpy as np

        ids = np.asarray(semantic_ids)
        while ids.ndim > 2 and ids.shape[-1] == 1:
            ids = ids[..., 0]
        if ids.ndim != 2:
            raise ValueError(
                f"semantic ID array must be HxW or HxWx1, got {ids.shape}"
            )
        color = np.zeros((*ids.shape, 3), dtype=np.uint8)
        for value in np.unique(ids):
            semantic_id = int(value)
            color[ids == value] = self.color_for_id(semantic_id)
        return color

    def mapping_document(self) -> Dict[str, Any]:
        ids = sorted(self.labels)
        return {
            "schema_version": 1,
            "palette": "sha256-semantic-world-v04",
            "ids": {
                str(semantic_id): {
                    "label": self.labels[semantic_id],
                    "color_rgb": list(self.color_for_id(semantic_id)),
                }
                for semantic_id in ids
            },
        }
